"""
@module cmod.custom.code_interface

ucd-iso-0 (His ruling 2026-10-10, AI-Notes/plans/UNO_CORE_DEMO_PLAN.md "the C-atom's CODE INTERFACE and
C-ISOTOPES"). His words: "in the CFunctionAtom details page, we will want to be able to see a code-interface that
shows it as though it is actual c-code, with the variables that come from board and pin specifications and other
data-sheets laid out in the code clearly with comment that should autogenerate saying which data-sheet they should
come from."

THE CODE INTERFACE of one atom (`render(atom_name, binding=None, manager=None)`) is its function's own C text,
VERBATIM from the project file (`line` to the matching closing brace — never re-indented, never re-authored), plus
one IDENTIFIER per datasheet-sourced thing the function touches:

  register    a register the atom's own manifest resources name (cmod.custom.analyse.resources, kind='register')
              -> soc (the ATmega328P datasheet, board.custom.register_fields_atmega328p) — SoC-fixed, never
              substituted (its value does not depend on which binding is in use)
  pin-macro   a declared board_config.h pin macro (an atom's own uses() resource, kind='declared') OR, for an
              '_init' atom with no uses() of its own (hal_led_init: its body touches only a GPIO-port register,
              LED_DDR/LED_BIT — themselves macros of LED_PIN, never the literal name), the SAME convention
              `cmod.custom.targets._init_counterpart_match` already established at the graph level: its runtime
              counterpart (hal_led, uses(LED_PIN)) names the macro, read here via the counterpart's own resolved
              board pin (a seeded graph's TargetDefinition row, pure, no binding needed) -> board (the UNO pinout
              document) + the soc pin's own pinout fact
  knob        a build-time setting substituted away by the PREPROCESSOR before the atom parser ever sees the body
              (UBRR0_VALUE, USART_U2X, F_CPU — never resources(), which only sees what survives preprocessing), found
              by scanning the function's own VERBATIM text for this small, named vocabulary (`_KNOB_FACTS`) ->
              programming (boards.txt — the actual baud/clock target these knobs are computed to hit)
  global      a file-scope global the atom reads/writes -> no datasheet (his design: "a global/library resource
  library     carries no datasheet" — kind/datasheet/datasheet_kind/fact all '', `why` says so)

`datasheet_kind`/`datasheet`/`fact` are STRUCTURAL — resolved from the project's own committed facts (never a
binding): a register's datasheet never depends on which board a solution targets (this slice: only the UNO's
atmega328p is materialized, UNO_CORE_DEMO_PLAN.md ucd-0b2b's own Phase-1 posture); a pin-macro's/knob's KIND is
likewise known without a binding (board_config.h's own literal default + the hardware-fixed BUTTON_PIN/SENSE_PIN
table already settle which pin they name). Only `value` depends on a binding (`binding=<solution>[@<board>]`,
resolved through `cmod.custom.binding` + `cmod.custom.claims.pin_claims` exactly as the hardware-chain scope door
already does) — without one, every identifier's `value` is '' (never guessed at a specific resolved number with no
binding in hand, even when the project's own board_config.h default WOULD settle one).

A literal occurrence of an identifier's own name inside the function's text gets ONE autogenerated comment on its
first line (`/* <- <kind>: <slug> — <fact> */`); when the name is never spelled out literally (macro indirection —
LED_PIN/BUTTON_PIN/SENSE_PIN are never written inside hal_led_init/hal_button_init/hal_sense_init's own bodies, only
their macro-expanded aliases are), the comment is anchored at the function's own FIRST line instead — a named,
honest fallback (never a guessed textual site), so EVERY identifier still gets exactly one comment. `rendered` is
the function's text with every comment inserted; `lines` carries the same per-line `comment` (joined with '; ' when
more than one identifier anchors to the same line) without the insertion (the page's own `code` column format, iso-1,
renders from this).

CIsotope rows (`isotopes_for_binding`) are the SAME render(), one per atom that has >= 1 datasheet-bound identifier,
with the binding's own PinClaims substituted into the text wherever the identifier's literal name IS spelled out
(a pin-macro/knob only — a register is never substituted, see above); `derive_isotope` is pure, called by the
firmware API's materialize idiom and by `GET /api/cmod/atoms/{atom}/isotopes`.
"""
import hashlib
