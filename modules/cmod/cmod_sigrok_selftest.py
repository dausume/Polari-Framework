"""cmod_sigrok_selftest - msv-3 (AI-Notes/plans/MEASURED_VS_SIMULATED_PLAN.md section 3; the user 2026-11-04: "anything with sigrok ... readings coming in
automatically is one critical case"): A METER READ THROUGH sigrok ANSWERS A STEP BY ITSELF (touch and confirm).

The checks, in order:
- sigrok-cli's '-O analog' lines are parsed. The lines are recorded from sigrok-cli 0.7.2 (Debian trixie, run 2026-11-04): the demo driver's
  'A0: -10.0000 V DC'. The meter's lines take its prefixes and flags.
- A value is kept only once it holds steady within one count of the meter.
- Without sigrok-cli the reader refuses by name.
- A STAND-IN sigrok-cli (a script replaying the recorded format, via SIGROK_CLI) drives the real subprocess path.
- The endpoint door takes a sigrok meter (its driver id from `sigrok-cli -L`: tekpower-tp4000ZC) and refuses a wrong driver or shell characters.
- On a test session, taking a measure step from the meter:
  - keeps the steady value as a reading (via usb-serial, the lines' sha256 as evidence), judged
  - no line = NO DATA; jumping lines = NOT STEADY; ohms = WRONG MODE
  - the Bridge's posted lines work the same; a continuity step is refused
  - the door
- When a real sigrok-cli is on this node, its demo driver is read for real.

    PYTHONPATH=.:modules python3 -m cmod.cmod_sigrok_selftest      # from polari-framework/
"""
import hashlib
import json
import os
import stat
import sys
import tempfile
import time
import types

passed = total = 0
BS = 'uno-light-on-desk'
NODE = BS + ':on-by-button'
HEX = 'c' * 64
REAL_DEMO = ['A0: -10.0000 V DC', 'A0: -10.0000 V DC', 'A0: -10.0000 V DC']   # sigrok-cli 0.7.2 --driver demo --samples 3 --channels A0 -O analog, verbatim
FAKE = r'''#!/bin/sh
# a STAND-IN sigrok-cli for the selftest: replays the '-O analog' format (FAKE_SIGROK_MODE picks what the "meter" says)
case "$1" in --version) echo "sigrok-cli 0.7.2 (stand-in)"; exit 0;; esac
case "$FAKE_SIGROK_MODE" in
  none) exit 0;;
  jumpy) printf 'P1: 14.10 mA DC AUTO\nP1: 14.90 mA DC AUTO\nP1: 13.70 mA DC AUTO\nP1: 15.20 mA DC AUTO\n';;
  ohm) printf 'P1: 0.0215 kΩ AUTO\nP1: 0.0215 kΩ AUTO\nP1: 0.0215 kΩ AUTO\n';;
  demo) printf 'A0: -10.0000 V DC\nA0: -10.0000 V DC\nA0: -10.0000 V DC\n';;
  zero) printf 'P1: 0.00 mA DC AUTO\nP1: 0.00 mA DC AUTO\nP1: 0.00 mA DC AUTO\nP1: 0.00 mA DC AUTO\n';;
  later) n=$(cat "$FAKE_SIGROK_COUNT" 2>/dev/null || echo 0); n=$((n+1)); echo $n > "$FAKE_SIGROK_COUNT"
         if [ $n -le 2 ]; then printf 'P1: 0.00 mA DC AUTO\nP1: 0.00 mA DC AUTO\nP1: 0.00 mA DC AUTO\nP1: 0.00 mA DC AUTO\n'; sleep 0.3
         else printf 'P1: 14.58 mA DC AUTO\nP1: 14.61 mA DC AUTO\nP1: 14.61 mA DC AUTO\nP1: 14.61 mA DC AUTO\n'; fi;;
  *) printf 'P1: 14.50 mA DC AUTO\nP1: 14.62 mA DC AUTO\nP1: 14.62 mA DC AUTO\nP1: 14.62 mA DC AUTO\n';;
esac
'''


def check(label, cond, extra=''):
    global passed, total
    total += 1
    passed += bool(cond)
    print('  [%s] %s %s' % ('\033[0;32mPASS\033[0m' if cond else '\033[0;31mFAIL\033[0m', label, extra if not cond else ''))


def _refused(fn):
    from cmod.custom.config_rows import ConfigRefused
    from instruments.custom.sigrok_reader import SigrokRefused
    try:
        fn()
    except (ConfigRefused, SigrokRefused) as e:
        return e.status
    return None


def main():
    from instruments.custom import sigrok_reader as SG
    p = [SG.parse_line(x) for x in REAL_DEMO + ['P1: 14.20 mA DC AUTO', 'P1: 4.997 V DC', 'P1: inf Ω', 'P1: 1.2 kΩ AUTO', '; CSV generated by libsigrok 0.5.2', 'g_atomic_ref_count_dec: assertion']]
    check('PARSE the recorded sigrok-cli 0.7.2 demo line (-10 V DC, channel A0); the meter\'s prefixes (14.20 mA = 0.0142 A) and flags (DC AUTO); an overload (inf) '
          'marked; kOhm scaled; a CSV comment and libsigrok\'s stderr noise ignored',
          p[0] == {'channel': 'A0', 'value': -10.0, 'unit': 'V', 'flags': ['DC'], 'raw': 'A0: -10.0000 V DC', 'overload': False}
          and abs(p[3]['value'] - 0.0142) < 1e-12 and p[3]['unit'] == 'A' and p[3]['flags'] == ['DC', 'AUTO'] and p[4]['value'] == 4.997
          and p[5]['overload'] and p[5]['unit'] == 'Ohm' and abs(p[6]['value'] - 1200) < 1e-9 and p[7] is None and p[8] is None, p)
    ok, _w = SG.steady([SG.parse_line('P1: %s mA DC' % v) for v in ('14.5', '14.62', '14.62', '14.63')], 1e-5)
    no, why = SG.steady([SG.parse_line('P1: %s mA DC' % v) for v in ('14.1', '14.9', '13.7', '15.2')], 1e-5)
    check('STEADY: the last 3 samples within one count (10 uA) give the value; jumping samples give none, said', abs(ok - 0.01463) < 1e-12 and no is None and 'not steady' in why,
          (ok, why))
    mixed = [SG.parse_line(x) for x in ('A0: -10.0000 V DC', 'A2: 0.0000 V DC', 'A0: -10.0000 V DC', 'A2: 2.0000 V DC', 'A0: -10.0000 V DC', 'A2: 4.0000 V DC')]
    check('STEADY on ONE channel: interleaved channels (the real demo driver prints A0..A3) are not mixed - the last sample\'s channel A2 is ramping: not steady',
          SG.steady(mixed, 1e-4)[0] is None and SG.steady(mixed[:-1], 1e-4)[0] == -10.0)
    saved = os.environ.pop('SIGROK_CLI', None)
    path = os.environ.get('PATH', '')
    os.environ['PATH'] = '/nonexistent'
    cap = SG.capability()
    check('NO sigrok-cli on the node: the capability says so, by name (apt install sigrok-cli), and a read refuses (409)',
          not cap['available'] and 'apt install sigrok-cli' in cap['why'] and _refused(lambda: SG.read('demo')) == 409, cap)
    os.environ['PATH'] = path
    tmp = tempfile.mkdtemp(prefix='fake-sigrok-')
    fake = os.path.join(tmp, 'sigrok-cli')
    open(fake, 'w').write(FAKE)
    os.chmod(fake, os.stat(fake).st_mode | stat.S_IEXEC)
    real = SG.binary()
    os.environ['SIGROK_CLI'] = fake
    os.environ['FAKE_SIGROK_MODE'] = 'demo'
    r = SG.read('demo')
    check('THE SUBPROCESS PATH (a stand-in sigrok-cli replaying the recorded format): argv = --driver demo --samples 12 -O analog; 3 samples of -10 V',
          r['argv'][1:] == ['--driver', 'demo', '--samples', '12', '-O', 'analog'] and [x['value'] for x in r['samples']] == [-10.0] * 3, r)
    check('a resource with shell characters or spaces is refused (422); an unlisted meter has no driver (422)',
          _refused(lambda: SG.argv_for('demo; rm -rf /', 1)) == 422 and _refused(lambda: SG.argv_for('demo conn=x', 1)) == 422
          and _refused(lambda: SG.driver_for('a-meter-nobody-checked')) == 422 and SG.driver_for('tekpower-tp4000zc') == 'tekpower-tp4000ZC')

    # a session on the light, as the procedure selftest builds it
    from cmod.cmod_light_topology_selftest import _manager, _seed
    from cmod.custom import bench_topology_spec as SP
    from cmod.custom import config_rows as R
    from cmod.custom import measure_points as MP
    from cmod.custom import measure_readings as MR
    from cmod.custom import test_procedures as TP
    from cmod.custom import test_sessions as TS
    from instruments.custom import captures as X
    from instruments.instruments_seed import SEED_ACCURACY
    m = _manager()
    _seed(m)
    SP.apply(m, BS)
    R.upsert(m, 'StructNodeRun', NODE + '#run1', node=NODE, outcome='reached', hex_sha256=HEX)
    R.upsert(m, 'StructNodeRunEdge', NODE + '#run1:e1', run=NODE + '#run1', order=1,
             collaterals='electrical circuit: ok - circuit uno-button-clock in state led-on (the LED lit); no finding')
    MP.derive(m, NODE)
    for a in SEED_ACCURACY:
        R.upsert(m, 'InstrumentAccuracy', a['name'], **{k: v for k, v in a.items() if k != 'name'})
    proc = TP.freeze(m, BS)
    unit = MR.add_unit(m, BS, {'hex_sha256': HEX})['name']
    s = TS.start(m, unit, {'procedure': proc['name'], 'mode': 'touch', 'who': 'a tester'})
    e1 = X.add_endpoint(m, {'name': 'bench-meter', 'instrument': 'tekpower-tp4000zc', 'transport': 'sigrok', 'resource': 'tekpower-tp4000ZC:conn=/dev/ttyUSB0'})
    e2 = X.add_endpoint(m, {'name': 'bad-meter', 'instrument': 'tekpower-tp4000zc', 'transport': 'sigrok', 'resource': 'uni-t-ut61e:conn=/dev/ttyUSB0'})
    e3 = X.add_endpoint(m, {'name': 'odd-meter', 'instrument': 'a-meter-nobody-checked', 'transport': 'sigrok', 'resource': 'x'})
    check('THE ENDPOINT DOOR takes a sigrok meter (transport sigrok, resource <driver>:conn=<port>, typed - never seeded); a resource of another driver 400; '
          'an unlisted meter 422', e1[0] == 201 and e2[0] == 400 and e3[0] == 422 and R.get(m, 'InstrumentEndpoint', 'bench-meter')['transport'] == 'sigrok', (e1[0], e2, e3))
    rows = proc['rows']
    led = next(x['name'] for x in rows if x['kind'] == 'measure' and x['mode'] == 'I dc')
    cont = next(x['name'] for x in rows if x['kind'] == 'continuity')
    os.environ['FAKE_SIGROK_MODE'] = 'led'
    t = TS.take(m, s['name'], led, {'endpoint': 'bench-meter'})
    raw = 'P1: 14.50 mA DC AUTO\nP1: 14.62 mA DC AUTO\nP1: 14.62 mA DC AUTO\nP1: 14.62 mA DC AUTO\n'
    check('TOUCH AND CONFIRM: the meter\'s steady 14.62 mA IS the reading - via usb-serial, the TP4000ZC\'s accuracy, the lines\' sha256 as evidence, the lines in the note; '
          'the step passes', t['verdict'] == 'pass' and t['via'] == 'usb-serial' and abs(t['value'] - 0.01462) < 1e-12 and t['instrument'] == 'tekpower-tp4000zc'
          and t['evidence_sha256'] == hashlib.sha256(raw.encode()).hexdigest() and 'P1: 14.62 mA DC AUTO' in t['note'] and t['session'] == s['name'], t)
    os.environ['FAKE_SIGROK_MODE'] = 'none'
    n = TS.take(m, s['name'], led, {'endpoint': 'bench-meter'})
    check('NO DATA CAME THROUGH: no line - its own outcome, naming the probe, the cable and the port (not the circuit); the sheet says no-data',
          n['verdict'] == 'no-data' and 'not the circuit' in n['note'] and next(x for x in TS.sheet(m, s['name'])['rows'] if x['step'] == led)['verdict'] == 'no-data', n)
    os.environ['FAKE_SIGROK_MODE'] = 'jumpy'
    j = TS.take(m, s['name'], led, {'endpoint': 'bench-meter'})
    os.environ['FAKE_SIGROK_MODE'] = 'ohm'
    w = TS.take(m, s['name'], led, {'endpoint': 'bench-meter'})
    check('NOT STEADY: jumping lines keep no reading; WRONG MODE: the meter reads ohms on a current step, said', j['verdict'] == 'not-steady' and w['verdict'] == 'wrong-mode'
          and 'Ohm' in w['note'], (j, w))
    b = TS.take(m, s['name'], led, {'instrument': 'tekpower-tp4000zc', 'lines': ['P1: 14.60 mA DC', 'P1: 14.60 mA DC', 'P1: 14.60 mA DC']})
    check('THE BRIDGE PATH: sigrok lines read on the person\'s machine and posted - the same judgement (pass)', b['verdict'] == 'pass' and 'Bridge' in b['note'], b)
    check('a continuity step is not a meter\'s to confirm (422); the sheet says touch for measure steps only',
          _refused(lambda: TS.take(m, s['name'], cont, {'endpoint': 'bench-meter'})) == 422
          and next(x for x in TS.sheet(m, s['name'])['rows'] if x['step'] == cont)['how'].startswith('the sheet'))
    import falcon
    import falcon.testing
    from cmod.cmod_measure_api import MeasureAPI
    app = falcon.App()
    MeasureAPI(polServer=types.SimpleNamespace(falconServer=app), manager=m)
    c = falcon.testing.TestClient(app)
    os.environ['FAKE_SIGROK_MODE'] = 'led'
    d = c.simulate_post('/api/cmod/bench-topology/%s/sessions/%s/steps/%s/take' % (BS, s['name'], led), body=json.dumps({'endpoint': 'bench-meter'}))
    d2 = c.simulate_post('/api/cmod/bench-topology/%s/sessions/%s/steps/%s/take' % (BS, s['name'], led), body=json.dumps({'endpoint': 'nope'}))
    check('the door: POST .../sessions/{s}/steps/{step}/take -> the judged reading; an unknown endpoint 404', d.status_code == 200 and d.json['verdict'] == 'pass'
          and d2.status_code == 404, (d.status_code, d.json))
    # PRIMING (the user: two hands - prime the step, then probe; it waits a configurable window and confirms once the data comes)
    from cmod.custom import test_primes as TPR

    def wait(name, secs=12):
        t0 = time.time()
        while time.time() - t0 < secs and R.get(m, 'TestStepPrime', name)['state'] == 'armed':
            time.sleep(0.1)
        return R.get(m, 'TestStepPrime', name)

    s2 = TS.start(m, unit, {'procedure': proc['name'], 'mode': 'touch', 'prime_window_s': '8'})
    os.environ['FAKE_SIGROK_MODE'] = 'later'
    os.environ['FAKE_SIGROK_COUNT'] = os.path.join(tmp, 'count')
    pr = TPR.prime(m, s2['name'], led, {'endpoint': 'bench-meter'})
    armed = next(x for x in TS.sheet(m, s2['name'])['rows'] if x['step'] == led)
    check('PRIME: the step is armed with the SESSION\'s window (8 s), it says to probe now; the sheet shows it armed; a second prime in the session is refused (409)',
          pr['state'] == 'armed' and pr['window_s'] == 8.0 and 'probe' in pr['note'] and armed['verdict'] == 'armed'
          and _refused(lambda: TPR.prime(m, s2['name'], led, {'endpoint': 'bench-meter'})) == 409, (pr, armed['verdict']))
    done = wait(pr['name'])
    rd = R.get(m, 'MeasurementReading', done['reading']) if done['reading'] else {}
    check('...the OPEN PROBE\'s steady 0 mA is not a confirmation (it kept waiting); once the probes touch, the meter settles at 14.61 mA: CONFIRMED by itself - the reading '
          'via usb-serial, judged, the step passes', done['state'] == 'confirmed' and abs(float(rd.get('value', 0)) - 0.01461) < 1e-12 and rd.get('via') == 'usb-serial'
          and int(open(os.environ['FAKE_SIGROK_COUNT']).read()) >= 3 and next(x for x in TS.sheet(m, s2['name'])['rows'] if x['step'] == led)['verdict'] == 'pass', (done, rd))
    os.environ['FAKE_SIGROK_MODE'] = 'zero'
    pz = TPR.prime(m, s2['name'], led, {'endpoint': 'bench-meter', 'window_s': 1.5})
    dz = wait(pz['name'])
    rz = R.get(m, 'MeasurementReading', dz['reading']) if dz['reading'] else {}
    check('THE WINDOW ENDS on a steady 0 mA (an open joint reads like that): KEPT-LAST - the value is kept and judged UNEXPLAINED, never dropped; the prime\'s own '
          'window (1.5 s) over the session\'s', dz['state'] == 'kept-last' and dz['window_s'] == 1.5 and rz.get('value') == 0.0
          and next(x for x in TS.sheet(m, s2['name'])['rows'] if x['step'] == led)['verdict'] == 'unexplained', (dz, rz.get('value')))
    os.environ['FAKE_SIGROK_MODE'] = 'none'
    pn = TPR.prime(m, s2['name'], led, {'endpoint': 'bench-meter', 'window_s': 1.0})
    dn = wait(pn['name'])
    check('NOTHING CAME THROUGH in the window: NO DATA (the probe, the cable, the port), no reading kept, the sheet says no-data',
          dn['state'] == 'no-data' and not dn['reading'] and 'not the circuit' in dn['note']
          and next(x for x in TS.sheet(m, s2['name'])['rows'] if x['step'] == led)['verdict'] == 'no-data', dn)
    pb = TPR.prime(m, s2['name'], led, {'instrument': 'tekpower-tp4000zc', 'window_s': 5})
    TPR.feed(m, pb['name'], ['P1: 0.00 mA DC', 'P1: 0.00 mA DC', 'P1: 0.00 mA DC'])
    mid = R.get(m, 'TestStepPrime', pb['name'])['state']
    fb = TPR.feed(m, pb['name'], ['P1: 14.60 mA DC', 'P1: 14.60 mA DC', 'P1: 14.60 mA DC'])
    check('THE BRIDGE primes the same way: its lines are fed in; the open probe\'s 0 keeps it armed, the settled 14.60 mA confirms it', mid == 'armed' and fb['state'] == 'confirmed', fb)
    pc = TPR.prime(m, s2['name'], led, {'instrument': 'tekpower-tp4000zc', 'window_s': 0.2})
    time.sleep(0.4)
    gone = next(x for x in TPR.primes(m, s2['name']) if x['name'] == pc['name'])
    TS.sheet(m, s2['name'])
    check('a Bridge prime past its window with no lines is finished when the sheet is read: no-data', R.get(m, 'TestStepPrime', pc['name'])['state'] == 'no-data', gone)
    # chain: a confirmation primes the next measure step with the same meter
    s3 = TS.start(m, unit, {'procedure': proc['name'], 'mode': 'touch'})
    measures = [x['name'] for x in rows if x['kind'] == 'measure' and x['node'] == NODE]
    for x in rows:
        if x['order'] < next(r['order'] for r in rows if r['name'] == measures[0]):
            TS.answer(m, s3['name'], x['name'], {'outcome': 'beep' if x['expect'].startswith('BEEP') else 'no-beep'} if x['kind'] == 'continuity'
                      else {'outcome': 'done'} if x['kind'] in ('setup', 'stimulus') else {'outcome': 'skipped'})
    first = next(x for x in TS.sheet(m, s3['name'])['rows'] if x['verdict'] == 'pending')
    TS.answer(m, s3['name'], first['step'], {'outcome': 'skipped'})
    TS.answer(m, s3['name'], measures[1], {'outcome': 'skipped'})
    TS.answer(m, s3['name'], measures[2], {'outcome': 'skipped'})
    pch = TPR.prime(m, s3['name'], led, {'instrument': 'tekpower-tp4000zc', 'window_s': 5, 'chain': 'true'})
    TPR.feed(m, pch['name'], ['P1: 14.60 mA DC'] * 3)
    nxt = [x for x in TPR.primes(m, s3['name']) if x['state'] == 'armed']
    check('CHAIN: the confirmation primes the NEXT pending measure step with the same meter and window (hands stay on the probes)',
          len(nxt) == 1 and nxt[0]['step'] == measures[4] and nxt[0]['chain'] and nxt[0]['window_s'] == 5.0,
          [(x['step'], x['state']) for x in TPR.primes(m, s3['name'])])
    TPR.cancel(m, nxt[0]['name'])
    check('cancel stops the wait; a non-measure step is not primed (422); the window is bounded (0 < s <= 600); "false" typed in the form is not true',
          R.get(m, 'TestStepPrime', nxt[0]['name'])['state'] == 'cancelled' and _refused(lambda: TPR.prime(m, s3['name'], cont, {'instrument': 'tekpower-tp4000zc'})) == 422
          and _refused(lambda: TPR.prime(m, s3['name'], led, {'instrument': 'tekpower-tp4000zc', 'window_s': 0})) == 422
          and not TPR.prime(m, s3['name'], led, {'instrument': 'tekpower-tp4000zc', 'chain': 'false'})['chain'])
    pd = c.simulate_post('/api/cmod/bench-topology/%s/sessions/%s/primes/%s/cancel' % (BS, s3['name'], [x for x in TPR.primes(m, s3['name']) if x['state'] == 'armed'][0]['name']), body='{}')
    pp = c.simulate_post('/api/cmod/bench-topology/%s/sessions/%s/steps/%s/prime' % (BS, s3['name'], led), body=json.dumps({'instrument': 'tekpower-tp4000zc', 'window_s': 5}))
    pl = c.simulate_post('/api/cmod/bench-topology/%s/sessions/%s/primes/%s/lines' % (BS, s3['name'], pp.json.get('name', 'x')), body=json.dumps({'lines': ['P1: 14.6 mA DC'] * 3}))
    pg = c.simulate_get('/api/cmod/bench-topology/%s/sessions/%s/primes' % (BS, s3['name']))
    check('the doors: cancel, prime, the Bridge\'s lines (confirmed), the list', pd.status_code == 200 and pp.status_code == 200 and pl.json.get('state') == 'confirmed'
          and pg.status_code == 200 and len(pg.json['rows']) >= 4, (pd.status_code, pp.json, pl.json))
    if real:
        os.environ['SIGROK_CLI'] = real
        rr = SG.read('demo:samplerate=1000', samples=3)
        check('THE REAL sigrok-cli on this node reads its demo driver (%s)' % SG.capability().get('version'), len(rr['samples']) >= 1, rr)
    else:
        print('  [skip] no real sigrok-cli on this node: the stand-in drove the subprocess path (the recorded 0.7.2 lines are the format)')
    if saved is not None:
        os.environ['SIGROK_CLI'] = saved
    else:
        os.environ.pop('SIGROK_CLI', None)
    here = os.path.dirname(os.path.abspath(__file__))
    flat = json.dumps(json.load(open(os.path.join(here, 'polari-app.json'))))
    iflat = json.dumps(json.load(open(os.path.join(here, '..', 'instruments', 'polari-app.json'))))
    check('the manifests list this selftest and the reader', 'cmod_sigrok_selftest' in flat and 'custom/sigrok_reader' in iflat)


if __name__ == '__main__':
    sys.path[:0] = [os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..')), os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))]
    main()
    print('\n%d/%d passed' % (passed, total))
    sys.exit(0 if passed == total else 1)
