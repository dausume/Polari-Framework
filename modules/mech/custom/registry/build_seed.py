#!/usr/bin/env python3
"""
@module mech.custom.registry.build_seed

Freezes the registry (materials_registry.json + part_material_roles.json
+ material_properties.py) into mech/mech_material_seed.py as Python
literals, through mech.custom.material_registry.options_from_registry /
preferences_from_registry. Edit the registry, not the seed:

    cd polari-framework && PYTHONPATH=.:modules python3 \\
        modules/mech/custom/registry/build_seed.py
"""
import os
import pprint
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'mech_material_seed.py')

from mech.custom.material_registry import (  # noqa: E402
    options_from_registry, preferences_from_registry,
)

HEADER = '''"""
@module mech.mech_material_seed

GENERATED by mech/custom/registry/build_seed.py from the registry data
in mech/custom/registry/ (materials_registry.json, part_material_roles.json
-> build_registry.py; property priors -> material_properties.py). DO NOT
EDIT BY HAND: change the registry and rerun build_seed.py.

mxc-1 seeds: SEED_MECH_MATERIAL_OPTIONS (one MechMaterialOption per
registry material: {n_opt} = 51 from the econ-core collab registry + 2
wood rows mech added) and SEED_MECH_MATERIAL_PREFERENCES (one
MechMaterialPreference per registry part category: {n_pref}).

Every property value is a textbook prior or a plan knob (its
provenance says which); the IARC rows are not yet checked against the
monographs (REGISTRY.json). -1 = no number held.

@consumers polariServer (seed_pairs), mech.mech_material_selftest
"""

PROV = 'mxc-1'

'''


def main():
    opts = options_from_registry()
    prefs = preferences_from_registry()
    body = HEADER.format(n_opt=len(opts), n_pref=len(prefs))
    body += 'SEED_MECH_MATERIAL_OPTIONS = '
    body += pprint.pformat(opts, width=79, sort_dicts=False) + '\n\n'
    body += 'SEED_MECH_MATERIAL_PREFERENCES = '
    body += pprint.pformat(prefs, width=79, sort_dicts=False) + '\n'
    with open(OUT, 'w') as f:
        f.write(body)
    print(f'wrote {os.path.normpath(OUT)}: {len(opts)} options, '
          f'{len(prefs)} preferences')
    return 0


if __name__ == '__main__':
    sys.exit(main())
