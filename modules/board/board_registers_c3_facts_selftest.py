"""board_registers_c3_facts_selftest - hal-3a: the C3 rows the generated HAL reads, checked FIELD FOR FIELD against the sources' own facts.

custom/evidence/esp32c3_hal3a_facts.json is a trimmed record of what Espressif's SVD and ESP-IDF v5.5.5's soc/*_reg.h say at each hal-3a row's
register and bit position (regenerated by tools/hal_evidence/esp32c3_hal3a_facts.py from the full sources, whose shas it names). For every
hal-3a field of board.custom.registers_esp32c3: the bit position and width = the SVD's = ESP-IDF's shift / mask; the field reset and the
register reset = the SVD's; the register offset = ESP-IDF's. One fact per field, no fact without a field. A proof that cannot fail is not
a proof, so three mutated copies - a moved bit, a wrong reset, a wrong offset - must each be caught.

    PYTHONPATH=.:modules python3 -m board.board_registers_c3_facts_selftest      # from polari-framework/ (standalone)
"""
import copy
import json
import os

_results = []
FACTS = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'custom', 'evidence', 'esp32c3_hal3a_facts.json')
SVD_SHA = '9ef33dbff56d807996fd8edfa4aa4ad008b5a861c241d36280caa0dedbbca41a'   # espressif/svd be20aa12 svd/esp32c3.svd


def check(label, cond, extra=''):
    _results.append(bool(cond))
    print('  [%s] %s%s' % ('PASS' if cond else 'FAIL', label, ('  ' + str(extra)[:300]) if (extra and not cond) else ''))


def compare(registers, fields, facts):
    """-> the disagreements in words ([] = every hal-3a field agrees with its fact)"""
    regs = {r['register']: r for r in registers}
    by = {(x['register'], x['field']): x for x in facts}
    why = []
    hal = [f for f in fields if f.get('part') == 'hal-3a']
    keys = {(f['register'], f['field']) for f in hal}
    why += ['no fact for %s.%s' % k for k in sorted(keys - set(by))] + ['a fact for no row: %s.%s' % k for k in sorted(set(by) - keys)]
    for f in hal:
        x = by.get((f['register'], f['field']))
        if not x:
            continue
        r = regs[f['register']]
        if (f['bit_lo'], f['width']) != (x['svd_bit_lo'], x['svd_width']) or f['bit_lo'] != x['idf_shift'] or (1 << f['width']) - 1 != x['idf_mask']:
            why.append('%s.%s bits [%d +%d]: SVD [%d +%d], ESP-IDF shift %d mask 0x%X' % (f['register'], f['field'], f['bit_lo'], f['width'], x['svd_bit_lo'],
                                                                                   x['svd_width'], x['idf_shift'], x['idf_mask']))
        if str(f['reset_value']) != x['svd_reset']:
            why.append('%s.%s reset %s: SVD %s' % (f['register'], f['field'], f['reset_value'], x['svd_reset']))
        if r['reset'].upper() != x['svd_register_reset'].upper():
            why.append('%s reset %s: SVD %s' % (f['register'], r['reset'], x['svd_register_reset']))
        if r['offset'] != x['idf_offset']:
            why.append('%s offset 0x%X: ESP-IDF %s 0x%X' % (f['register'], r['offset'], x['idf_register'], x['idf_offset']))
    return why


def run():
    from board.custom import esp32c3_evidence as EV
    from board.custom import registers_esp32c3 as R
    doc = json.load(open(FACTS))
    src = doc['sources']
    check('the facts name their sources: the SVD file (espressif/svd be20aa12, sha256 9ef33dbf...), ESP-IDF v5.5.5 + the sha of each *_reg.h read, and the '
          'SAME TRM file every C3 row cites (esp32c3_evidence.TRM_SHA)',
          src['svd']['sha256'] == SVD_SHA and src['esp_idf']['version'] == 'v5.5.5' and len(src['esp_idf']['headers_sha256']) == 6
          and src['trm']['sha256'] == EV.TRM_SHA, (src['svd']['sha256'][:12], src['esp_idf']['version'], src['trm']['sha256'][:12]))
    _, hal = R.part('hal-3a')
    check('one fact per hal-3a field (%d)' % len(hal), len(doc['facts']) == len(hal) and len({(x['register'], x['field']) for x in doc['facts']}) == len(hal),
          (len(doc['facts']), len(hal)))
    why = compare(R.REGISTERS, R.FIELDS, doc['facts'])
    check('every hal-3a field: bits = the SVD\'s = ESP-IDF\'s shift / mask; field + register reset = the SVD\'s; register offset = ESP-IDF\'s', not why, '; '.join(why[:5]))
    for label, mutate in (('a moved bit (ONETIME_CHANNEL bit_lo + 1)', lambda F, G: next(f for f in F if f['field'] == 'ONETIME_CHANNEL').update(
                              bit_lo=next(f for f in F if f['field'] == 'ONETIME_CHANNEL')['bit_lo'] + 1)),
                          ('a wrong reset (LEDC_CH0_CONF1 DUTY_INC 0)', lambda F, G: next(f for f in F if f['register'] == 'LEDC_CH0_CONF1_REG'
                                                                                          and f['field'] == 'DUTY_INC').update(reset_value='0')),
                          ('a wrong offset (SYSTIMER_COMP0_LOAD_REG + 4)', lambda F, G: next(r for r in G if r['register'] == 'SYSTIMER_COMP0_LOAD_REG').update(
                              offset=next(r for r in G if r['register'] == 'SYSTIMER_COMP0_LOAD_REG')['offset'] + 4))):
        F, G = copy.deepcopy(R.FIELDS), copy.deepcopy(R.REGISTERS)
        mutate(F, G)
        check('control: %s is caught' % label, compare(G, F, doc['facts']) != [])
    total, ok = len(_results), sum(_results)
    print('\n%d/%d checks passed' % (ok, total))
    return ok == total


if __name__ == '__main__':
    import sys
    sys.exit(0 if run() else 1)
